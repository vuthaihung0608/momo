def t(key: str, lang: str = "vi") -> str:
    """Translate UI key into active language ('vi' or 'en')."""
    pack = TRANSLATIONS.get(lang, TRANSLATIONS["vi"])
    return pack.get(key, TRANSLATIONS["vi"].get(key, key))


def cat_label(category: str, lang: str = "vi") -> str:
    """Return localized display label for a canonical category key."""
    pack = CATEGORY_LABELS.get(lang, CATEGORY_LABELS["vi"])
    return pack.get(category, category)


def fmt_month_label(ym: str, lang: str = "vi", is_latest: bool = False) -> str:
    """Format '2026-11' as 'Tháng 11/2026 (Hiện tại)' or 'Nov 2026 (Current)'."""
    if ym == "ALL":
        return t("all_months", lang)
    parts = ym.split("-")
    if len(parts) == 2:
        y, m = parts[0], parts[1]
        if lang == "en":
            en_m = {"01": "Jan", "02": "Feb", "03": "Mar", "04": "Apr", "05": "May", "06": "Jun",
                    "07": "Jul", "08": "Aug", "09": "Sep", "10": "Oct", "11": "Nov", "12": "Dec"}
            base = f"{en_m.get(m, m)} {y}"
        else:
            base = f"Tháng {m}/{y}"
        return f"{base} {t('current_tag', lang)}" if is_latest else base
    return ym
